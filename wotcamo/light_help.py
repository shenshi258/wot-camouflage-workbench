def topic(name):
    name={'−':'缩小','＋':'放大','适应':'适应窗口'}.get(name,name)
    return Help(name.rstrip(' ▾'), TEXT[name])


def option(topic_name, value, app=None):
    if topic_name == '效果模式':
        return Help(value, MODES.get(value, TEXT[topic_name]))
    if topic_name == '流水方向':
        return Help(value, DIRECTIONS.get(value, TEXT[topic_name]))
    if topic_name == '预设' and app is not None:
        record = app.preset_library.get(value)
        if record:
            cfg=record['配方']
            return Help(value, '%s\n\n模式：%s；%d 种颜色，每色 %s 秒；呼吸 %s 秒，峰值 %s，暗相 %s。\n方向：%s，每米延迟 %s 秒。\n\n选择后先填入当前表单，局部编辑还需点击应用。' %
                        (record['说明'],cfg.get('效果模式','流水呼吸'),len(cfg['颜色']),cfg['每色秒数'],
                         cfg['呼吸周期秒数'],cfg['峰值倍率'],cfg['暗相系数'],cfg['流水方向'],cfg['每米延迟秒数']))
    return topic(topic_name)
